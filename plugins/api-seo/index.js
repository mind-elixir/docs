const fs = require('node:fs/promises')
const path = require('node:path')

const API_DIR = path.join('docs', 'api')
const GENERATED_MARKER = 'automatically generated by API Documenter'
const PRODUCT_NAME = 'Mind Elixir Core'
const DESCRIPTION_SUFFIX = `Part of the ${PRODUCT_NAME} JavaScript mind map API reference.`

const KIND_PATTERN =
  /^(?<owner>.+?)\s+(?<kind>property|method|method signature|function|class|interface|type alias|variable|constructor|enumeration|namespace|package)$/

function toPlainText(value) {
  return value
    .replace(/<[^>]+>/g, ' ')
    .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')
    .replace(/&gt;/g, '>')
    .replace(/&lt;/g, '<')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&amp;/g, '&')
    .replace(/`([^`]*)`/g, '$1')
    .replace(/\s+/g, ' ')
    .trim()
}

function truncate(value, max) {
  if (value.length <= max) return value
  const cut = value.slice(0, max)
  const lastSpace = cut.lastIndexOf(' ')
  return `${(lastSpace > max * 0.6 ? cut.slice(0, lastSpace) : cut).trim()}…`
}

function parseHeading(lines) {
  for (let index = 0; index < lines.length; index += 1) {
    const match = /^##\s+(.+?)\s*$/.exec(lines[index])
    if (!match) continue
    const label = match[1]
    const kindMatch = KIND_PATTERN.exec(label)
    return {
      lineIndex: index,
      label,
      owner: kindMatch?.groups.owner,
      kind: kindMatch?.groups.kind,
    }
  }
  return undefined
}

function parseSummary(lines, fromIndex) {
  const collected = []
  let started = false

  for (let index = fromIndex + 1; index < lines.length; index += 1) {
    const line = lines[index].trim()

    if (line.startsWith('**Signature:**')) break
    if (line.startsWith('#')) break
    if (line.startsWith('```')) break

    if (!line) {
      if (started) break
      continue
    }

    if (line.startsWith('|') || line.startsWith('<')) continue

    started = true
    collected.push(line)
  }

  const text = toPlainText(collected.join(' '))
  return text || undefined
}

function unique(values) {
  return [...new Set(values.filter(Boolean))]
}

function createEntry(raw) {
  if (!raw.includes(GENERATED_MARKER)) return undefined

  const lines = raw.split(/\r?\n/)
  const heading = parseHeading(lines)
  if (!heading) return undefined

  const summary = parseSummary(lines, heading.lineIndex)
  const { label, owner, kind } = heading

  if (label === 'API Reference') {
    return {
      title: 'mind-elixir API Reference',
      description: `Complete TypeScript API reference for the ${PRODUCT_NAME} JavaScript mind map library: classes, interfaces, methods, properties and types.`,
      keywords: [
        'mind-elixir API',
        'javascript mind map API',
        'Mind Elixir Core',
        'mind-elixir',
        'mind map library',
      ],
    }
  }

  if (kind === 'package') {
    return {
      title: `${owner} API overview`,
      description: `Browse the mind-elixir package API: the MindElixir class plus its methods, properties, interfaces and helper types for building JavaScript mind maps.`,
      keywords: unique([owner, 'mind-elixir API', 'MindElixir class', PRODUCT_NAME, 'javascript mind map']),
    }
  }

  const description = summary
    ? truncate(`${label} — ${summary.replace(/\.$/, '')}. ${DESCRIPTION_SUFFIX}`, 158)
    : truncate(`${label}. ${DESCRIPTION_SUFFIX}`, 158)

  return {
    title: label,
    description,
    keywords: unique([
      label,
      owner,
      owner ? `${owner} ${kind}` : undefined,
      'mind-elixir',
      PRODUCT_NAME,
      'javascript mind map',
      'mindmap',
      'API reference',
    ]).slice(0, 8),
  }
}

async function loadApiPages(siteDir) {
  const apiDir = path.join(siteDir, API_DIR)
  let fileNames

  try {
    fileNames = await fs.readdir(apiDir)
  } catch (error) {
    if (error.code === 'ENOENT') return {}
    throw error
  }

  const pages = {}

  await Promise.all(
    fileNames
      .filter((fileName) => /\.mdx?$/.test(fileName))
      .map(async (fileName) => {
        const raw = await fs.readFile(path.join(apiDir, fileName), 'utf8')
        const entry = createEntry(raw)
        if (entry) {
          pages[fileName.replace(/\.mdx?$/, '')] = entry
        }
      }),
  )

  return pages
}

module.exports = function apiSeoPlugin(context) {
  return {
    name: 'api-seo',

    async loadContent() {
      return { pages: await loadApiPages(context.siteDir) }
    },

    async contentLoaded({ content, actions }) {
      actions.setGlobalData(content)
    },
  }
}
